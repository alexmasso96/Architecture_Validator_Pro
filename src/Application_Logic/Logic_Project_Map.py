# Rendering
# ---------------------------------------------------------------------------

def _prefix(names: List[str]) -> str:
    pre = os.path.commonprefix(names)
    return pre[:pre.rfind("_") + 1] if "_" in pre else ""


def _port_entry(row: dict, f: Optional[dict], short_name: str) -> str:
    if row["variable"] and not row["function"]:
        text = f"{short_name}→var {row['variable']}"
    elif f:
        args = ", ".join(f"{_short(a.get('type', ''))} {a.get('name', '')}".strip()
                         for a in f.get("parameters") or [])
        sig = f.get("signature") or ""
        ret = _short(sig.split(row["function"])[0].strip() if row["function"] in sig
                     else f.get("return_type") or "void")
        where = f":{f['line_start']}" if f.get("line_start") else ""
        text = f"{short_name}({args})→{ret}{where}"
        if row["variable"]:
            text += f" var {row['variable']}"
    else:
        text = f"{short_name} (no function in the binary)"
    if row["direction"] and row["direction"] != "provided":
        text += f" [{row['direction']}]"
    return text


def _render_ports(mm: dict) -> List[str]:
    functions = mm["functions"]
    by_file = defaultdict(list)
    for r in mm["ports"]:
        f = functions.get(r["function"]) if r["function"] else None
        by_file[(f or {}).get("file") or ("(no source found)" if f else "(not matched)")].append(r)
    lines = [f"## PORTS ({len(mm['ports'])}) — port → function(params) → return :line"]
    for path in sorted(by_file):
        rows = by_file[path]
        with_fn = [r for r in rows if r["function"]]
        pp = _prefix([r["name"] for r in with_fn])
        fp = _prefix([r["function"] for r in with_fn])
        items = []
        for r in rows:
            fits = pp and fp and r["function"] and r["name"][len(pp):] == r["function"][len(fp):]
            short = r["name"][len(pp):] if fits else (
                f"{r['name']}→{r['function']}" if r["function"] else r["name"])
            items.append(_port_entry(r, functions.get(r["function"]), short))
        head = f"{path}: {pp}X → {fp}X — " if pp and fp else f"{path}: "
        lines.append(head + "; ".join(items))
    return lines


def _render_model(mm: dict, budget: int) -> str:
    functions = mm["functions"]
    scope = mm["scope"]
    files = sorted({functions[n]["file"] for n in scope if functions.get(n, {}).get("file")})
    head = [f"# MODEL MAP — {mm.get('model_name', '')}"
            + (f", release {mm['release']}" if mm.get("release") else ""),
            f"{len(scope)} functions in {len(files)} files, {len(mm['ports'])} ports, "
            f"{len(mm['globals'])} globals. The release has "
            f"{mm.get('release_function_count', 0)} functions. Built from the compiled "
            f"ELF and the C source. {TOOLS_HINT}", ""]
    head += _render_ports(mm) + [""]

    if mm["entries"]:
        head.append("## RUN FROM (2 levels, calls in source order)")
        for e in mm["entries"]:
            f = functions.get(e, {})
            up = f.get("called_by") or []
            head.append(e + (f"  (called by {', '.join(up[:4])})" if up else ""))
            for c in f.get("calls") or ():
                if c not in functions or c in mm["entries"]:
                    continue
                sub = [x for x in functions[c].get("calls") or () if x in functions]
                head.append(f"  {c}" + (f" → {', '.join(sub)}" if sub else ""))
        head.append("")

    if mm["globals"]:
        head.append("## DATA — globals this model uses")
        for g, typ in mm["globals"].items():
            fields = mm["structures"].get(typ)
            head.append(f"{g}: {typ}" + (" {" + ", ".join(
                f"{x.get('name')} {_short(x.get('type', ''))}" for x in fields) + "}"
                if fields else ""))
        head.append("")

    text = "\n".join(head) + "## FUNCTIONS — most central first\n"
    room = budget - len(text) - 120
    rank = mm["rank"]
    shown, dropped = [], 0
    for n in sorted(scope, key=lambda x: (-rank.get(x, 0), x)):
        f = functions.get(n, {})
        loc = f" @{f['file']}:{f.get('line_start', 0)}" if f.get("file") else " @(binary only)"
        parts = [(f.get("signature") or n) + loc]
        calls = [c for c in f.get("calls") or () if c in functions or c in scope]
        if calls:
            parts.append("calls " + ", ".join(calls))
        up = f.get("called_by") or []
        if up:
            parts.append("called by " + ", ".join(up[:3]) + (f" +{len(up) - 3}" if len(up) > 3 else ""))
        if f.get("writes_vars"):
            parts.append("writes " + ", ".join(f["writes_vars"]))
        reads = [v for v in f.get("reads_vars") or []
                 if _root(v) in mm["globals"] and not any(
                     o != v and (o.startswith(v + ".") or o.startswith(v + "["))
                     for o in f.get("reads_vars") or [])]
        if reads:
            parts.append("reads " + ", ".join(reads))
        line = "- " + " | ".join(parts)
        if len(line) + 1 > room:
            dropped += 1
            continue
        shown.append(line)
        room -= len(line) + 1
    text += "\n".join(shown)
    if dropped:
        text += f"\n(+{dropped} less central functions not shown — use the tools)"
    return text[:budget]


def _render_project(pm: dict, budget: int) -> str:
    models = pm["models"]
    lines = [f"# PROJECT MAP" + (f" — release {pm['release']}" if pm.get("release") else ""),
             f"{len(models)} models, {sum(m['ports'] for m in models)} ports, "
             f"{pm.get('release_function_count', 0)} functions. This is the overview: for "
             f"detail on one model, use that model's map. {TOOLS_HINT}", ""]
    sched = pm["scheduler"]
    if sched:
        lines.append("## WHAT RUNS THE MODELS (calls in source order)")
        tops = sorted(n for n, s in sched.items() if not s["called_by"])
        owner = {f: m["name"] for m in models for f in m["entries"]}

        def walk(n, depth, seen):
            calls = sched.get(n, {}).get("calls", [])
            marks = [f"{c} [{owner[c]}]" if c in owner else c for c in calls]
            lines.append("  " * depth + n + (f" → {', '.join(marks)}" if marks else ""))
            for c in calls:
                if c in sched and c not in seen and depth < 3:
                    seen.add(c)
                    walk(c, depth + 1, seen)
        for t in tops:
            walk(t, 0, {t})
        lines.append("")
    lines.append("## MODELS")
    for m in models:
        dirs = sorted({os.path.dirname(f) or "." for f in m["files"]})
        names = ", ".join(os.path.basename(f) for f in m["files"])
        lines.append(f"### {m['name']} — {m['ports']} ports, {m['functions']} functions in "
                     f"{', '.join(d + '/' for d in dirs)} ({names})")
        if m["entries"]:
            lines.append("Run from: " + ", ".join(m["entries"]))
        if m["top"]:
            lines.append("Key functions: " + ", ".join(m["top"]))
    lines.append("")
    if pm["between_models"]:
        lines.append("## CALLS BETWEEN MODELS")
        for pair, calls in sorted(pm["between_models"].items()):
            lines.append(f"{pair}: " + ", ".join(calls[:6]) + (f" +{len(calls) - 6}" if len(calls) > 6 else ""))
        lines.append("")
    if pm["shared_globals"]:
        lines.append("## DATA SHARED BETWEEN MODELS")
        for g, s in sorted(pm["shared_globals"].items()):
            lines.append(f"{g}: {s['type']} — written by {', '.join(s['written_by']) or 'none'}"
                         + (f", read by {', '.join(s['read_by'])}" if s["read_by"] else ""))
    text = "\n".join(lines)
    if len(text) > budget:
        cut = text[:budget - 60]
        text = cut[:cut.rfind("\n")] + "\n(cut to fit — ask about one model for more)"
    return text


def render(mind_map: dict, budget_chars: int) -> str:
    if mind_map.get("kind") == KIND_PROJECT:
        return _render_project(mind_map, budget_chars)
    return _render_model(mind_map, budget_chars)
