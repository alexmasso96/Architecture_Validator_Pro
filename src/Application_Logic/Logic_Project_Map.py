"""
Project maps (mind map v3)
==========================
What an AI assistant reads first about the code: a compact table of contents
built from the release's Code Map (ELF + source index) and the architecture
table's ports. Nothing in it is generated by AI or guessed from keywords: a
port's function is the symbol its row matched.

Two kinds, both rendered to fit a character budget:

* A model map covers one architecture model: its ports with the function and
  signature behind each, the call tree from whatever runs it, the globals it
  uses with their struct fields, and its functions ranked by how central they
  are to its ports (PageRank over the call graph), so the budget keeps the most
  important ones.
* The project map covers the whole release in less detail: what runs every
  model, each model's files, entry points and key functions, the calls between
  models and the globals they share. A small model can then pick one model's
  map instead of reading everything.

The stored form is JSON with only what the renderer needs; rendering happens on
request, so the budget can change without a rebuild.
"""
from __future__ import annotations

import os
from collections import defaultdict
from typing import Dict, Iterable, List, Optional

BUILDER_VERSION = "3.0"
KIND_MODEL = "model"
KIND_PROJECT = "project"

TOOLS_HINT = ("For anything not shown, use get_function(name), get_call_graph(name), "
              "search_code(text) or read_file(path).")
_SHORT_TYPES = {"uint8_t": "u8", "uint16_t": "u16", "uint32_t": "u32", "uint64_t": "u64",
                "int8_t": "s8", "int16_t": "s16", "int32_t": "s32", "int64_t": "s64"}
_KEPT_FIELDS = ("calls", "file", "line_start", "signature", "reads_vars", "writes_vars",
                "parameters", "return_type")


def _short(t: str) -> str:
    t = " ".join((t or "").split())
    return _SHORT_TYPES.get(t, t)


def _root(var: str) -> str:
    for sep in (".", "[", "->"):
        var = var.split(sep)[0]
    return var


# ---------------------------------------------------------------------------
# Graph helpers
# ---------------------------------------------------------------------------

def _callers(functions: Dict[str, dict]) -> Dict[str, List[str]]:
    out: Dict[str, List[str]] = defaultdict(list)
    for name, f in functions.items():
        for c in f.get("calls") or ():
            if c in functions and name not in out[c]:
                out[c].append(name)
    return out


def pagerank(nodes: Iterable[str], functions: Dict[str, dict], personal: Iterable[str],
             iterations: int = 40, damping: float = 0.85,
             reverse: bool = False) -> Dict[str, float]:
    """How central each node is, walking the call graph from the ``personal``
    nodes (a model's ports and entry points). ``reverse`` walks from callee to
    caller, which favours the functions that coordinate others."""
    nodes = list(dict.fromkeys(nodes))
    if not nodes:
        return {}
    present = set(nodes)
    targets = {n: [c for c in (functions.get(n, {}).get("calls") or ()) if c in present]
               for n in nodes}
    if reverse:
        flipped = {n: [] for n in nodes}
        for n, out in targets.items():
            for c in out:
                flipped[c].append(n)
        targets = flipped
    seeds = set(personal) & present or present
    base = {n: (1.0 / len(seeds) if n in seeds else 0.0) for n in nodes}
    rank = dict(base)
    for _ in range(iterations):
        nxt = {n: (1 - damping) * base[n] for n in nodes}
        for n in nodes:
            out = targets[n]
            if out:
                share = damping * rank[n] / len(out)
                for c in out:
                    nxt[c] += share
            else:
                for s in seeds:
                    nxt[s] += damping * rank[n] / len(seeds)
        rank = nxt
    return rank


def centrality(nodes: List[str], functions: Dict[str, dict], personal: List[str]) -> Dict[str, float]:
    """Both directions, so a map keeps the helpers everyone calls and the
    functions that call everyone, not just one kind."""
    down = pagerank(nodes, functions, personal)
    up = pagerank(nodes, functions, nodes, reverse=True)
    top_down, top_up = max(down.values(), default=0) or 1, max(up.values(), default=0) or 1
    return {n: down.get(n, 0) / top_down + up.get(n, 0) / top_up for n in nodes}


