# Building
# ---------------------------------------------------------------------------

def _port_rows(ports: List[dict], functions: Dict[str, dict], globals_: Dict[str, str]):
    rows = []
    for p in ports or ():
        name = str(p.get("name") or "").strip()
        if not name:
            continue
        fn = str(p.get("function") or p.get("operation") or "").strip()
        var = str(p.get("variable") or "").strip()
        if fn and fn not in functions and fn in globals_ and not var:
            fn, var = "", fn    # the port matched a variable, not a function
        rows.append({"name": name, "function": fn, "variable": var,
                     "direction": str(p.get("direction") or "").strip().lower()})
    return rows


def model_scope(code_map: dict, ports: List[dict]) -> List[str]:
    """A model's functions: its port functions and everything defined in the
    same source files."""
    functions = code_map.get("functions") or {}
    port_fns = {p.get("function") or p.get("operation") for p in ports or ()}
    files = {functions[f]["file"] for f in port_fns if f in functions and functions[f].get("file")}
    scope = [n for n, f in functions.items() if f.get("file") in files]
    scope += [f for f in port_fns if f in functions and f not in scope]
    return scope


def build_model_map(code_map: dict, model_id: int, model_name: str, ports: List[dict],
                    release_name: str = "", generated_at: str = "") -> dict:
    functions = code_map.get("functions") or {}
    globals_ = code_map.get("global_variables") or {}
    rows = _port_rows(ports, functions, globals_)
    scope = model_scope(code_map, rows)
    in_scope = set(scope)
    callers = _callers(functions)
    entries = sorted({c for f in scope for c in callers.get(f, []) if c not in in_scope})
    rank = centrality(scope + entries, functions,
                      [r["function"] for r in rows if r["function"]] + entries)
    kept = {}
    for n in set(scope) | set(entries):
        f = functions[n]
        kept[n] = {k: f.get(k) for k in _KEPT_FIELDS if f.get(k) not in (None, "", [])}
        kept[n]["called_by"] = callers.get(n, [])
    used = sorted({_root(v) for n in scope for v in
                   (functions[n].get("reads_vars") or []) + (functions[n].get("writes_vars") or [])
                   if _root(v) in globals_} | {r["variable"] for r in rows if r["variable"] in globals_})
    structures = code_map.get("structures") or {}
    return {
        "builder_version": BUILDER_VERSION, "kind": KIND_MODEL,
        "model_id": model_id, "model_name": model_name, "release": release_name,
        "generated_at": generated_at, "source_parser": code_map.get("source_parser"),
        "release_function_count": len(functions),
        "ports": rows, "scope": scope, "entries": entries,
        "rank": {n: round(v, 6) for n, v in rank.items()},
        "functions": kept,
        "globals": {g: globals_[g] for g in used},
        "structures": {globals_[g]: structures[globals_[g]] for g in used
                       if globals_[g] in structures},
    }


def build_project_map(code_map: dict, models: List[tuple], release_name: str = "",
                      generated_at: str = "") -> dict:
    """``models`` = [(model_id, model_name, ports)]."""
    functions = code_map.get("functions") or {}
    globals_ = code_map.get("global_variables") or {}
    callers = _callers(functions)
    owner: Dict[str, str] = {}
    out_models = []
    for model_id, name, ports in models:
        rows = _port_rows(ports, functions, globals_)
        scope = model_scope(code_map, rows)
        for f in scope:
            owner.setdefault(f, name)
        in_scope = set(scope)
        entries = sorted({c for f in scope for c in callers.get(f, []) if c not in in_scope})
        # The functions that coordinate the model, not its leaf helpers.
        up = pagerank(scope, functions, scope, reverse=True)
        top = sorted(scope, key=lambda n: (-up.get(n, 0), n))[:8]
        files = sorted({functions[f]["file"] for f in scope if functions[f].get("file")})
        out_models.append({"model_id": model_id, "name": name, "ports": len(rows),
                           "functions": len(scope), "files": files, "entries": entries,
                           "top": top})

    # What runs the models: functions outside every model that call into one,
    # walked up to the top.
    outside = {n for n in functions if n not in owner}
    roots = sorted({c for f in owner for c in callers.get(f, []) if c in outside})
    frontier = list(roots)
    scheduler = set(roots)
    while frontier:
        n = frontier.pop()
        for c in callers.get(n, []):
            if c in outside and c not in scheduler:
                scheduler.add(c)
                frontier.append(c)
    sched = {n: {"calls": [c for c in functions[n].get("calls") or () if c in functions],
                 "called_by": [c for c in callers.get(n, []) if c in scheduler]}
             for n in scheduler}

    between = defaultdict(list)
    for f, m in owner.items():
        for c in functions[f].get("calls") or ():
            other = owner.get(c)
            if other and other != m:
                between[f"{m} → {other}"].append(f"{f}→{c}")

    writers, readers = defaultdict(set), defaultdict(set)
    for f, m in owner.items():
        for v in functions[f].get("writes_vars") or ():
            writers[_root(v)].add(m)
        for v in functions[f].get("reads_vars") or ():
            readers[_root(v)].add(m)
    shared = {g: {"type": globals_.get(g, ""), "written_by": sorted(writers[g]),
                  "read_by": sorted(readers[g] - writers[g])}
              for g in set(writers) | set(readers)
              if g in globals_ and len(writers[g] | readers[g]) > 1}

    return {
        "builder_version": BUILDER_VERSION, "kind": KIND_PROJECT,
        "release": release_name, "generated_at": generated_at,
        "source_parser": code_map.get("source_parser"),
        "release_function_count": len(functions), "models": out_models,
        "scheduler": sched, "between_models": dict(between), "shared_globals": shared,
    }


