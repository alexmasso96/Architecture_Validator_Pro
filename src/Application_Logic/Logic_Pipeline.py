def _expand(value: str, environ: Mapping[str, str], key: str) -> str:
    def replace(m):
        name = m.group(1)
        if name not in environ:
            raise PipelineError(f"[{key}] uses ${{{name}}}, which is not set.")
        return environ[name]
    return _VAR_RE.sub(replace, value)


def _lines(value: str) -> List[str]:
    return [line.strip() for line in value.splitlines() if line.strip()]


def _int(raw: str, key: str, low: int, high: Optional[int] = None) -> int:
    try:
        value = int(raw)
    except ValueError:
        raise PipelineError(f"[{key}] must be a whole number, not {raw!r}.") from None
    if value < low or (high is not None and value > high):
        limit = f"{low}..{high}" if high is not None else f"at least {low}"
        raise PipelineError(f"[{key}] must be {limit}, not {value}.")
    return value


def _parse_symbols(values: List[str], resolve) -> List[Tuple[str, str]]:
    """``COMPONENT=path`` per line; a bare path uses the default component."""
    out: List[Tuple[str, str]] = []
    for line in values:
        component, sep, path = line.partition("=")
        if not sep:
            component, path = DEFAULT_COMPONENT, line
        component = component.strip()
        if any(component == c for c, _p in out):
            raise PipelineError(f"[inputs] symbols: component {component!r} is "
                                "listed twice.")
        out.append((component, resolve(path.strip())))
    return out


def _parameter_columns(titles: List[str]) -> List[str]:
    """Workbook columns holding parameter ports; each title gives its direction."""
    unclear = [t for t in titles if ct.column_direction(t) is None]
    if unclear:
        raise PipelineError("[columns] parameter_columns need \"required\" or "
                            f"\"provided\" in the title: {', '.join(unclear)}.")
    if len(set(titles)) != len(titles):
        raise PipelineError("[columns] parameter_columns lists a column twice.")
    return titles


def _password(section: Mapping[str, str], environ: Mapping[str, str]) -> Optional[str]:
    """The project password for the chosen mode. An empty one is an error, never
    a fallback: an unset pipeline variable must not change how the file is
    stored, and the app cannot reopen a file created with an empty password."""
    mode = section.get("encryption", "none").strip().lower()
    if mode not in ENCRYPTION_MODES:
        raise PipelineError(f"[security] encryption must be one of "
                            f"{', '.join(ENCRYPTION_MODES)}, not {mode!r}.")
    if mode == "none":
        if section.get("password"):
            raise PipelineError("[security] has a password but encryption = none.")
        return None
    if mode == "config":
        password = section.get("password", "")
        source = "[security] password"
    else:
        var = section.get("password_env", DEFAULT_PASSWORD_ENV).strip()
        password = environ.get(var, "")
        source = f"environment variable {var}"
    if not password:
        raise PipelineError(f"encryption = {mode} but {source} is empty.")
    if is_blacklisted(password):
        raise PipelineError(f"{source} is a reserved test password that would "
                            "store the project unencrypted.")
    return password


def load_config(path: str, environ: Optional[Mapping[str, str]] = None) -> PipelineConfig:
    """Parse a ``.cfg`` file. Relative paths are relative to the file; ``${VAR}``
    reads the environment (values only, never the password itself)."""
    environ = os.environ if environ is None else environ
    parser = configparser.ConfigParser(interpolation=None)
    try:
        with open(path, encoding="utf-8") as f:
            parser.read_file(f)
    except OSError as e:
        raise PipelineError(f"Cannot read {path}: {e}") from e
    except configparser.Error as e:
        raise PipelineError(f"Cannot parse {path}: {e}") from e

    for section in parser.sections():
        if section not in _KNOWN_KEYS:
            raise PipelineError(f"Unknown section [{section}].")
        unknown = set(parser[section]) - _KNOWN_KEYS[section]
        if unknown:
            raise PipelineError(f"Unknown key in [{section}]: "
                                f"{', '.join(sorted(unknown))}.")

    def get(section: str, key: str, default: str = "") -> str:
        raw = parser.get(section, key, fallback=default)
        return _expand(raw, environ, f"{section}] {key}".replace("] ", "."))

    base = os.path.dirname(os.path.abspath(path))

    def resolve(p: str) -> str:
        return os.path.normpath(os.path.join(base, p))

    workbook = get("inputs", "workbook").strip()
    if not workbook:
        raise PipelineError("[inputs] workbook is required.")
    symbols = _parse_symbols(_lines(get("inputs", "symbols")), resolve)
    if not symbols:
        raise PipelineError("[inputs] symbols is required.")
    folder = get("output", "folder").strip()
    if not folder:
        raise PipelineError("[output] folder is required.")

    cfg = PipelineConfig(
        name=get("project", "name").strip() or Path(path).stem,
        workbook=resolve(workbook),
        symbols=symbols,
        output_folder=resolve(folder),
        release=get("project", "release").strip() or "pipeline",
        main_sheet=get("inputs", "main_sheet").strip() or DEFAULT_MAIN_SHEET,
        source=[resolve(p) for p in _lines(get("inputs", "source"))],
        source_exclude=[resolve(p) for p in _lines(get("inputs", "source_exclude"))],
        object_pattern=get("inputs", "object_pattern").strip() or "**/*.o",
        function_column=get("columns", "function_column").strip() or FUNCTION_TARGET,
        port_column=get("columns", "port_column").strip() or PORT_TARGET,
        variable_column=get("columns", "variable_column").strip() or VARIABLE_TARGET,
        parameter_columns=_parameter_columns(_lines(get("columns", "parameter_columns"))),
        min_match_score=_int(get("test", "min_match_score", str(DEFAULT_MIN_MATCH_SCORE)),
                             "test.min_match_score", 0, 100),
        min_parameter_score=_int(get("test", "min_parameter_score",
                                     str(ct.DEFAULT_VARIABLE_SCORE)),
                                 "test.min_parameter_score", 0, 100),
        max_unmatched=_int(get("test", "max_unmatched", "0"), "test.max_unmatched",
                           NO_UNMATCHED_LIMIT),
        password=_password(parser["security"] if parser.has_section("security") else {},
                           environ),
    )
    try:
        cfg.strict = parser.getboolean("test", "strict", fallback=False)
    except ValueError:
        raise PipelineError("[test] strict must be true or false.") from None
    objects = get("inputs", "objects").strip()
    cfg.objects = resolve(objects) if objects else None

    missing = [p for p in ([cfg.workbook] + [s[1] for s in cfg.symbols] + cfg.source
                           + ([cfg.objects] if cfg.objects else []))
               if not os.path.exists(p)]
    if missing:
        raise PipelineError("Not found: " + ", ".join(missing))
    return cfg


