def evaluate_gate(model_counts: Mapping[str, Mapping[str, int]],
                  max_unmatched: int) -> dict:
    """{passed, totals, reasons} for a run's {model: {verdict: count}}."""
    totals: Dict[str, int] = {}
    for counts in model_counts.values():
        for verdict, n in counts.items():
            totals[verdict] = totals.get(verdict, 0) + n
    reasons: List[str] = []
    tested = sum(n for v, n in totals.items()
                 if v not in (ct.NO_RESULT, ct.NOT_MATCHED))
    if not tested:
        reasons.append("Nothing was tested.")
    unmatched = totals.get(ct.NOT_MATCHED, 0)
    if max_unmatched != NO_UNMATCHED_LIMIT and unmatched > max_unmatched:
        reasons.append(f"{unmatched} port(s) without a match "
                       f"(allowed: {max_unmatched}).")
    for verdict, n in sorted(totals.items()):
        if verdict not in (ct.PASSED, ct.ENTRY_POINT, ct.NO_RESULT, ct.NOT_MATCHED):
            reasons.append(f"{n} port(s) {verdict}.")
    return {"passed": not reasons, "totals": totals, "reasons": reasons}
