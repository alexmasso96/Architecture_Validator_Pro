"""
Pipeline (CLI) run inputs and verdict: the ``.cfg`` file, the architecture
workbook, and the pass/fail rule of a whole run.

The workbook is one .xlsx generated by the pipeline. Every sheet is one
architecture model (the sheet name is the model name) with the column titles in
its first row; one reserved sheet maps models to main functions: first column
the model name, second column a main function, a repeated model adds another.

Pass/fail rule:
  * Passed and Entry point are OK, No Result (a retired or deleted port, or a
    port with no parameter in that column) is ignored.
  * Not Matched fails the run once there are more than ``max_unmatched`` of
    them; ``max_unmatched = -1`` never fails on them.
  * Anything else (Failed, No Data) always fails the run, as does a run where
    no port could be tested.

Pure module: no DB or HTTP. ``cli.main`` drives the run.
"""
from __future__ import annotations

import configparser
import os
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, Iterable, List, Mapping, Optional, Tuple

from Application_Logic import Logic_CallTree_Test as ct
from Application_Logic.Logic_Crypto import is_blacklisted
from Application_Logic.Logic_Column_Layout import DEFAULT_COLUMN_LAYOUT
from Application_Logic.Logic_Table_Import import _build_table, _clean_cell

ENCRYPTION_MODES = ("none", "config", "env")
DEFAULT_PASSWORD_ENV = "ARCH_PASSWORD"
DEFAULT_MAIN_SHEET = "Main Functions"
DEFAULT_MIN_MATCH_SCORE = 90
DEFAULT_COMPONENT = "Main"
NO_UNMATCHED_LIMIT = -1        # max_unmatched value: any number is accepted

# Table columns a workbook title may fill directly. The rest of the default
# layout (Match/Init/Cyclic/Review) is owned by the app.
FUNCTION_TARGET = "Mapped Func"
PORT_TARGET = "Input Port"
VARIABLE_TARGET = "Mapped Parameter"
TEST_MATCH_COLUMN = f"{FUNCTION_TARGET} (Match)"
_FILLABLE = {"TC. ID", PORT_TARGET, FUNCTION_TARGET, VARIABLE_TARGET, "Port State"}
_DEFAULT_NAMES = {c[0] for c in DEFAULT_COLUMN_LAYOUT}

_KNOWN_KEYS = {
    "project": {"name", "release"},
    "inputs": {"workbook", "main_sheet", "symbols", "source", "source_exclude",
               "objects", "object_pattern"},
    "columns": {"function_column", "port_column", "variable_column", "parameter_columns"},
    "test": {"min_match_score", "min_parameter_score", "max_unmatched", "strict"},
    "security": {"encryption", "password", "password_env"},
    "output": {"folder"},
}
_VAR_RE = re.compile(r"\$\{([^}]+)\}")


class PipelineError(ValueError):
    """A problem with the run's setup (not a test result): exit code 2."""


@dataclass
class PipelineConfig:
    name: str
    workbook: str
    symbols: List[Tuple[str, str]]
    output_folder: str
    release: str = "pipeline"
    main_sheet: str = DEFAULT_MAIN_SHEET
    source: List[str] = field(default_factory=list)
    source_exclude: List[str] = field(default_factory=list)
    objects: Optional[str] = None
    object_pattern: str = "**/*.o"
    function_column: str = FUNCTION_TARGET
    port_column: str = PORT_TARGET
    variable_column: str = VARIABLE_TARGET
    parameter_columns: List[str] = field(default_factory=list)
    min_match_score: int = DEFAULT_MIN_MATCH_SCORE
    min_parameter_score: int = ct.DEFAULT_VARIABLE_SCORE
    max_unmatched: int = 0
    strict: bool = False
    password: Optional[str] = None


@dataclass
class ArchitectureWorkbook:
    models: Dict[str, List[dict]]        # model name -> table rows, in sheet order
    columns: List[str]                   # table columns, first-seen order
    mains: Dict[str, List[str]]          # model name -> main functions


