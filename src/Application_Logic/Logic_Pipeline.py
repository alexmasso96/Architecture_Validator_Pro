def _title_map(cfg: PipelineConfig) -> Dict[str, str]:
    return {cfg.function_column: FUNCTION_TARGET, cfg.port_column: PORT_TARGET,
            cfg.variable_column: VARIABLE_TARGET}


def _sheet_rows(sheet: str, columns: List[str], rows: List[dict],
                cfg: PipelineConfig) -> Tuple[List[str], List[dict]]:
    """A model sheet as (table columns, table rows); blank rows are dropped."""
    if cfg.function_column not in columns:
        raise PipelineError(f"Sheet {sheet!r} has no {cfg.function_column!r} column.")
    titles = _title_map(cfg)
    targets = [titles.get(c, c) for c in columns]
    if any(t in titles for t in cfg.parameter_columns):
        raise PipelineError("[columns] parameter_columns can't also be the function, "
                            "port or variable column.")
    for title, target in zip(columns, targets):
        if target in _DEFAULT_NAMES and target not in _FILLABLE:
            raise PipelineError(f"Sheet {sheet!r}: column {title!r} is reserved "
                                "by the app.")
    if len(set(targets)) != len(targets):
        raise PipelineError(f"Sheet {sheet!r}: two columns fill the same table "
                            "column; rename one or change [columns].")
    out = [{target: {"text": str(row.get(title, ""))}
            for title, target in zip(columns, targets)}
           for row in rows if any(str(v).strip() for v in row.values())]
    return targets, out


def _read_mains(rows: List[List[str]], models: Dict[str, list]) -> Dict[str, List[str]]:
    mains: Dict[str, List[str]] = {}
    for number, row in enumerate(rows[1:], 2):
        model = str(row[0]).strip() if len(row) > 0 else ""
        function = str(row[1]).strip() if len(row) > 1 else ""
        if not model and not function:
            continue
        if not model or not function:
            raise PipelineError(f"Main functions sheet, row {number}: needs both "
                                "a model name and a function.")
        if model not in models:
            raise PipelineError(f"Main functions sheet, row {number}: no sheet "
                                f"named {model!r}.")
        names = mains.setdefault(model, [])
        if function not in names:
            names.append(function)
    too_many = [m for m, names in mains.items() if len(names) > ct.MAX_MAINS]
    if too_many:
        raise PipelineError(f"More than {ct.MAX_MAINS} main functions for: "
                            + ", ".join(too_many))
    return mains


def read_workbook(cfg: PipelineConfig) -> ArchitectureWorkbook:
    """Read every sheet in one file open (EDR machines intercept each open)."""
    if Path(cfg.workbook).suffix.lower() not in (".xlsx", ".xlsm"):
        raise PipelineError("[inputs] workbook must be an .xlsx file.")
    import openpyxl
    try:
        wb = openpyxl.load_workbook(cfg.workbook, read_only=True, data_only=True)
    except Exception as e:  # noqa: BLE001 — bad/locked file → a clear setup error
        raise PipelineError(f"Cannot read {cfg.workbook}: {e}") from e
    try:
        sheets = {name: [[_clean_cell(c) for c in row]
                         for row in wb[name].iter_rows(values_only=True)]
                  for name in wb.sheetnames}
    finally:
        wb.close()

    if cfg.main_sheet not in sheets:
        raise PipelineError(f"The workbook has no {cfg.main_sheet!r} sheet.")
    models: Dict[str, List[dict]] = {}
    columns: List[str] = []
    for name, raw in sheets.items():
        if name == cfg.main_sheet:
            continue
        titles, rows = _build_table(raw, 0)
        if not titles:
            raise PipelineError(f"Sheet {name!r} has no column titles.")
        targets, models[name] = _sheet_rows(name, titles, rows, cfg)
        columns.extend(t for t in targets if t not in columns)
    if not models:
        raise PipelineError("The workbook has no model sheets.")
    return ArchitectureWorkbook(models, columns, _read_mains(sheets[cfg.main_sheet], models))


def build_layout(columns: List[str], parameter_columns: Iterable[str] = ()) -> list:
    """The default table layout plus the workbook's own columns, as static text
    in front of the review columns. Parameter columns become Variable Search
    columns, to the right of the function column they're tested against."""
    parameters = [c for c in parameter_columns if c in columns]
    extras = [(c, "Static Text", True, 140) for c in columns
              if c not in _DEFAULT_NAMES and c not in parameters]
    search = [column for title in parameters
              for column in ((title, "Variable Search", True, 160),
                             (match_column(title), "Static Text", True, 160))]
    names = [c[0] for c in DEFAULT_COLUMN_LAYOUT]
    review = names.index("Review Status")
    variable = names.index(VARIABLE_TARGET)
    return (DEFAULT_COLUMN_LAYOUT[:variable] + search
            + DEFAULT_COLUMN_LAYOUT[variable:review] + extras + DEFAULT_COLUMN_LAYOUT[review:])


def match_column(title: str) -> str:
    return f"{title} (Match)"


def report_suffix(title: str) -> str:
    """A file-name-safe part for a parameter column's report."""
    return re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")


